class ItemGeneratorTest {

    private static final UUID PROJECT_ID = UUID.fromString("0f8fad5b-d9cb-469f-a165-70867728950e");
    private static final String PROJECT_KEY = "eldoria_rpg";
    private static final String DIRECTORY = "src/autogenerated/java/net/onelitefeather/vulpes/item/";
    private static final String KEYS_PATH = DIRECTORY + "CustomItemKeys.java";
    private static final String ITEMS_PATH = DIRECTORY + "CustomItems.java";
    private static final String ENTRIES_PATH = DIRECTORY + "CustomItemEntries.java";
    private static final String REGISTRY_PATH = ENTRIES_PATH;

    @TempDir
    Path tempDir;

    private ItemRepository repository;

    @BeforeEach
    void setUp() {
        repository = mock(ItemRepository.class);
    }

    @Test
    void generatesMaterialFromComponents() {
        generate(item("sword", component("stelaris:material", "\"minecraft:diamond_sword\"")));

        assertTrue(readRegistry().contains("ItemStack.builder(Material.DIAMOND_SWORD)"),
                "The material should be read from the stelaris:material component");
    }

    @Test
    void generatesAmountFromComponents() {
        generate(item("stack",
                component("stelaris:material", "\"minecraft:stone\""),
                component("stelaris:amount", "5")));

        assertTrue(readRegistry().contains(".amount(5)"),
                "A non-default amount should be emitted as an amount call");
    }

    @Test
    void omitsAmountCallWhenAmountIsDefault() {
        generate(item("single", component("stelaris:material", "\"minecraft:stone\"")));

        assertFalse(readRegistry().contains(".amount("),
                "An item with the default amount of 1 should not emit an amount call");
    }

    @Test
    void sortsLoreByOrderIndex() {
        generate(withLore(item("lore_item", component("stelaris:material", "\"minecraft:stone\"")),
                lore("Zeile 2", 2),
                lore("Zeile 1", 1)));

        String code = readRegistry();
        assertTrue(code.contains("DataComponents.LORE, List.of(Component.text(\"Zeile 1\"), Component.text(\"Zeile 2\"))"),
                "The lore lines should be emitted in orderIndex order but was:\n" + code);
    }

    @Test
    void emitsEnchantmentWithRegistryKeyAndLevel() {
        generate(withEnchantments(item("enchanted"), enchantment("minecraft:sharpness", 5)));

        assertTrue(readRegistry().contains("new EnchantmentList(Map.of(RegistryKey.<Enchantment>of(\"minecraft:sharpness\"), 5))"),
                "The enchantment should be emitted as a registry key with its level");
    }

    @Test
    void emitsGenericComponentWithEscapedJson() {
        generate(item("named",
                component("stelaris:material", "\"minecraft:stone\""),
                component("minecraft:custom_name", "{\"text\":\"Schwert\"}")));

        String code = readRegistry();
        assertTrue(code.contains("\"minecraft:custom_name\", \"{\\\"text\\\":\\\"Schwert\\\"}\""),
                "A generic component should be emitted as an escaped key and JSON string but was:\n" + code);
    }

    @Test
    void generatedSourceContainsNoEscapedOrUnresolvedPlaceholders() {
        generate(withEnchantments(withLore(item("full",
                        component("stelaris:material", "\"minecraft:diamond_sword\""),
                        component("stelaris:amount", "5"),
                        component("minecraft:custom_name", "{\"text\":\"Schwert\"}")),
                lore("Zeile 1", 1)),
                enchantment("minecraft:sharpness", 5)));

        String code = readRegistry();
        assertFalse(code.contains("\\$"), "The source must not contain a backslash in front of a placeholder but was:\n" + code);
        assertFalse(code.contains("$"), "The source must not contain any unresolved placeholder but was:\n" + code);
    }

    @Test
    void sortsItemFieldsByVariableName() {
        generate(
                item("zeta", component("stelaris:material", "\"minecraft:stone\"")),
                item("alpha", component("stelaris:material", "\"minecraft:stone\"")),
                item("mid", component("stelaris:material", "\"minecraft:stone\""))
        );

        String code = readRegistry();
        int alpha = code.indexOf("CustomItemKeys.ALPHA");
        int mid = code.indexOf("CustomItemKeys.MID");
        int zeta = code.indexOf("CustomItemKeys.ZETA");
        assertTrue(alpha >= 0 && mid >= 0 && zeta >= 0, "All three entries should be generated but was:\n" + code);
        assertTrue(alpha < mid && mid < zeta, "The fields should be sorted by variable name but was:\n" + code);
    }

    @Test
    void rejectsUnknownComponentKeyWithKeyInMessage() {
        IllegalArgumentException exception = assertThrows(IllegalArgumentException.class, () -> generate(item("broken",
                component("stelaris:material", "\"minecraft:stone\""),
                component("minecraft:not_a_component", "\"x\""))),
                "An unknown data component must abort the generation");

        assertTrue(exception.getMessage().contains("minecraft:not_a_component"),
                "The message should name the unknown component but was: " + exception.getMessage());
    }

    @Test
    void rejectsUnknownEnchantmentWithNameInMessage() {
        IllegalArgumentException exception = assertThrows(IllegalArgumentException.class,
                () -> generate(withEnchantments(item("bad_enchant"), enchantment("minecraft:not_an_enchantment", 1))),
                "An unknown enchantment must abort the generation");

        assertTrue(exception.getMessage().contains("minecraft:not_an_enchantment"),
                "The message should name the unknown enchantment but was: " + exception.getMessage());
    }

    @Test
    void writesPublicNonExtendableKeysInterface() {
        generate(item("sword", component("stelaris:material", "\"minecraft:stone\"")));

        String code = read(KEYS_PATH);
        assertTrue(code.contains("public interface CustomItemKeys") && code.contains("@ApiStatus.NonExtendable"),
                "The keys must be a public non extendable interface but was:\n" + code);
    }

    @Test
    void emitsKeyConstantWithProjectNamespaceAndItemPath() {
        generate(item("frostmourne", component("stelaris:material", "\"minecraft:stone\"")));

        assertTrue(read(KEYS_PATH).contains("Key FROSTMOURNE = Key.key(\"eldoria_rpg\", \"frostmourne\");"),
                "The key constant must hold the project namespace and the item path but was:\n" + read(KEYS_PATH));
    }

    @Test
    void writesPackagePrivateSealedItemsInterface() {
        generate(item("sword", component("stelaris:material", "\"minecraft:stone\"")));

        String code = read(ITEMS_PATH);
        assertTrue(code.contains("\nsealed interface CustomItems permits CustomItem {"),
                "The items must be a package private sealed interface but was:\n" + code);
    }

    @Test
    void emitsItemConstantResolvedThroughImpl() {
        generate(item("sword", component("stelaris:material", "\"minecraft:stone\"")));

        assertTrue(read(ITEMS_PATH).contains("CustomItem SWORD = CustomItemImpl.get(CustomItemKeys.SWORD);"),
                "The constant must be resolved through CustomItemImpl but was:\n" + read(ITEMS_PATH));
    }

    @Test
    void writesPackagePrivateEntriesClassWithPrivateConstructor() {
        generate(item("sword", component("stelaris:material", "\"minecraft:stone\"")));

        String code = read(ENTRIES_PATH);
        assertTrue(code.contains("\nfinal class CustomItemEntries {") && code.contains("private CustomItemEntries()"),
                "The entries must be a final package private class with a private constructor but was:\n" + code);
    }

    @Test
    void emitsEntryAsCustomItemImplWithKeyAndItemStack() {
        generate(item("sword", component("stelaris:material", "\"minecraft:stone\"")));

        assertTrue(read(ENTRIES_PATH).contains("new CustomItemImpl(CustomItemKeys.SWORD, ItemStack.builder(Material.STONE)"),
                "The entry must hold the key and the item stack but was:\n" + read(ENTRIES_PATH));
    }

    @Test
    void wrapsGenericComponentsIntoDecoderCall() {
        generate(item("named",
                component("stelaris:material", "\"minecraft:stone\""),
                component("minecraft:custom_name", "{\"text\":\"Schwert\"}")));

        String code = read(ENTRIES_PATH);
        assertTrue(code.contains("ItemComponentDecoder.apply(") && !code.contains("withComponents"),
                "Generic components must go through the vulpes-base decoder but was:\n" + code);
    }

    @Test
    void generatedEntriesContainNoLogicOrNestedTypes() {
        generate(item("named",
                component("stelaris:material", "\"minecraft:stone\""),
                component("minecraft:custom_name", "{\"text\":\"Schwert\"}")));

        for (String path : List.of(KEYS_PATH, ITEMS_PATH, ENTRIES_PATH)) {
            String code = read(path);
            assertFalse(code.contains("private static") || code.contains("for (") || code.contains("record "),
                    path + " must not declare helpers or nested types but was:\n" + code);
        }
    }

    @Test
    void sortsConstantsByIdentifierInEveryFile() {
        generate(
                item("zeta", component("stelaris:material", "\"minecraft:stone\"")),
                item("alpha", component("stelaris:material", "\"minecraft:stone\"")));

        for (String path : List.of(KEYS_PATH, ITEMS_PATH, ENTRIES_PATH)) {
            String code = read(path);
            assertTrue(code.indexOf("ALPHA") >= 0 && code.indexOf("ALPHA") < code.indexOf("ZETA"),
                    "The constants should be sorted by identifier in " + path + " but was:\n" + code);
        }
    }

    @Test
    void writesEmptyEntriesWithoutItems() {
        generate();

        for (String path : List.of(KEYS_PATH, ITEMS_PATH, ENTRIES_PATH)) {
            assertTrue(Files.exists(tempDir.resolve(path)), "Without items " + path + " must still be written");
        }
        assertTrue(read(ENTRIES_PATH).contains("return List.of();"),
                "Without items the entries must be an empty list but was:\n" + read(ENTRIES_PATH));
    }

    @Test
    void doesNotWriteItemsJson() {
        generate(item("sword", component("stelaris:material", "\"minecraft:stone\"")));

        assertFalse(Files.exists(tempDir.resolve("src/main/resources/items.json")),
                "The registry data must live in Java code only");
    }

    @Test
    void generatedFilesCompileAgainstVulpesBaseStubs() throws IOException {
        generate(withEnchantments(withLore(item("compiled",
                        component("stelaris:material", "\"minecraft:diamond_sword\""),
                        component("stelaris:amount", "5"),
                        component("minecraft:custom_name", "{\"text\":\"Schwert\"}")),
                lore("Zeile 1", 1)),
                enchantment("minecraft:sharpness", 5)),
                item("my-item.v2", component("stelaris:material", "\"minecraft:stone\"")));
        List<String> sources = new ArrayList<>(writeStubs());
        sources.addAll(List.of(KEYS_PATH, ITEMS_PATH, ENTRIES_PATH));

        JavaSourceAssertions.assertCompiles(tempDir, sources.toArray(String[]::new));
    }

    @Test
    void generatedFilesCompileWithoutItems() throws IOException {
        generate();
        List<String> sources = new ArrayList<>(writeStubs());
        sources.addAll(List.of(KEYS_PATH, ITEMS_PATH, ENTRIES_PATH));

        JavaSourceAssertions.assertCompiles(tempDir, sources.toArray(String[]::new));
    }

    @Test
    void generatingTwiceOnTheSameInstanceProducesIdenticalSource() {
        ItemGenerator generator = generatorWith(
                withLore(item("sword",
                        component("stelaris:material", "\"minecraft:diamond_sword\""),
                        component("minecraft:custom_name", "{\"text\":\"Schwert\"}")),
                        lore("Zeile 1", 1)),
                item("stone", component("stelaris:material", "\"minecraft:stone\"")));

        generator.generate(tempDir, PROJECT_ID);
        List<String> first = List.of(read(KEYS_PATH), read(ITEMS_PATH), read(ENTRIES_PATH));
        generator.generate(tempDir, PROJECT_ID);

        assertEquals(first, List.of(read(KEYS_PATH), read(ITEMS_PATH), read(ENTRIES_PATH)),
                "A second generate call on the same instance must not change or duplicate the output");
    }

    /**
     * Writes minimal stand-ins for the hand written vulpes-base types the generated code depends on.
     */
    private List<String> writeStubs() throws IOException {
        Map<String, String> stubs = new LinkedHashMap<>();
        stubs.put("stub/net/onelitefeather/vulpes/VulpesKey.java",
                "package net.onelitefeather.vulpes;\npublic interface VulpesKey { net.kyori.adventure.key.Key key(); }\n");
        stubs.put("stub/net/onelitefeather/vulpes/registry/Registry.java",
                "package net.onelitefeather.vulpes.registry;\npublic interface Registry<T> { }\n");
        stubs.put("stub/net/onelitefeather/vulpes/registry/RegistryFactory.java",
                "package net.onelitefeather.vulpes.registry;\n"
                        + "public final class RegistryFactory {\n"
                        + "    private RegistryFactory() { }\n"
                        + "    public static <T> Registry<T> of(java.util.List<T> entries) { return new Registry<>() { }; }\n"
                        + "}\n");
        stubs.put("stub/net/onelitefeather/vulpes/item/CustomItem.java",
                "package net.onelitefeather.vulpes.item;\n"
                        + "public sealed interface CustomItem extends net.onelitefeather.vulpes.VulpesKey, CustomItems permits CustomItemImpl {\n"
                        + "    net.minestom.server.item.ItemStack itemStack();\n}\n");
        stubs.put("stub/net/onelitefeather/vulpes/item/ItemComponentDecoder.java",
                "package net.onelitefeather.vulpes.item;\n"
                        + "final class ItemComponentDecoder {\n"
                        + "    private ItemComponentDecoder() { }\n"
                        + "    static net.minestom.server.item.ItemStack.Builder apply(net.minestom.server.item.ItemStack.Builder builder, String... keyAndJson) { return builder; }\n"
                        + "}\n");
        stubs.put("stub/net/onelitefeather/vulpes/item/CustomItemImpl.java",
                "package net.onelitefeather.vulpes.item;\n"
                        + "import net.kyori.adventure.key.Key;\n"
                        + "import net.minestom.server.item.ItemStack;\n"
                        + "import net.onelitefeather.vulpes.registry.Registry;\n"
                        + "import net.onelitefeather.vulpes.registry.RegistryFactory;\n"
                        + "record CustomItemImpl(Key key, ItemStack itemStack) implements CustomItem {\n"
                        + "    static final Registry<CustomItem> REGISTRY = RegistryFactory.of(CustomItemEntries.entries());\n"
                        + "    static CustomItem get(Key key) { return null; }\n"
                        + "}\n");
        for (Map.Entry<String, String> stub : stubs.entrySet()) {
            Path file = tempDir.resolve(stub.getKey());
            Files.createDirectories(file.getParent());
            Files.writeString(file, stub.getValue(), StandardCharsets.UTF_8);
        }
        return new ArrayList<>(stubs.keySet());
    }

    private String read(String path) {
        try {
            return Files.readString(tempDir.resolve(path), StandardCharsets.UTF_8);
        } catch (IOException e) {
            throw new AssertionError("The file " + path + " should have been generated", e);
        }
    }

    @Test
    void generationRunsInReadOnlyTransaction() throws NoSuchMethodException {
        boolean readOnly = ItemGenerator.class.getMethod("generate", Path.class, UUID.class).isAnnotationPresent(ReadOnly.class);

        assertTrue(readOnly, "generate must be annotated with @ReadOnly so lazy item components can be loaded");
    }

    @Test
    void rejectsTwoKeysWithSameJavaIdentifierNamingBothKeys() {
        IllegalArgumentException exception = assertThrows(IllegalArgumentException.class, () -> generate(
                item("my-item", component("stelaris:material", "\"minecraft:stone\"")),
                item("my.item", component("stelaris:material", "\"minecraft:stone\""))),
                "Two keys that map to the same identifier must abort the generation");

        assertTrue(exception.getMessage().contains("my-item") && exception.getMessage().contains("my.item"),
                "The message must name both keys but was: " + exception.getMessage());
    }

    private ItemGenerator generatorWith(ItemEntity... items) {
        when(repository.findByProjectId(eq(PROJECT_ID), any(Pageable.class)))
                .thenReturn(Page.of(List.of(items), Pageable.UNPAGED, (long) items.length));
        return new ItemGenerator(repository);
    }

    private void generate(ItemEntity... items) {
        when(repository.findByProjectId(eq(PROJECT_ID), any(Pageable.class)))
                .thenReturn(Page.of(List.of(items), Pageable.UNPAGED, (long) items.length));

        new ItemGenerator(repository).generate(tempDir, PROJECT_ID);
    }

    private String readRegistry() {
        try {
            return Files.readString(tempDir.resolve(REGISTRY_PATH), StandardCharsets.UTF_8);
        } catch (IOException e) {
            throw new AssertionError("The generated item file should have been generated at " + REGISTRY_PATH, e);
        }
    }

    private static ItemEntity item(String key, ItemComponentEntity... components) {
        ProjectEntity project = new ProjectEntity();
        project.setKey(PROJECT_KEY);
        ItemEntity entity = new ItemEntity();
        entity.setProject(project);
        entity.setKey(key);
        entity.setLore(List.of());
        entity.setEnchantments(List.of());
        entity.setComponents(List.of(components));
        return entity;
    }

    private static ItemEntity withLore(ItemEntity entity, ItemLoreEntity... lore) {
        entity.setLore(List.of(lore));
        return entity;
    }

    private static ItemEntity withEnchantments(ItemEntity entity, ItemEnchantmentEntity... enchantments) {
        entity.setEnchantments(List.of(enchantments));
        return entity;
    }

    private static ItemComponentEntity component(String key, String jsonValue) {
        return new ItemComponentEntity(UUID.fromString("00000000-0000-0000-0000-000000000001"), key, jsonValue);
    }

    private static ItemLoreEntity lore(String text, int orderIndex) {
        return new ItemLoreEntity(UUID.fromString("00000000-0000-0000-0000-000000000002"), text, orderIndex);
    }

    private static ItemEnchantmentEntity enchantment(String name, int level) {
        return new ItemEnchantmentEntity(UUID.fromString("00000000-0000-0000-0000-000000000003"), name, (short) level, false);
    }
}
