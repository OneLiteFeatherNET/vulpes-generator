package net.onelitefeather.vulpes.generator.generation.java;

import net.onelitefeather.vulpes.generator.generation.JavaSourceAssertions;
import io.micronaut.data.model.Page;
import io.micronaut.data.model.Pageable;
import io.micronaut.transaction.annotation.ReadOnly;
import net.onelitefeather.vulpes.api.model.FontEntity;
import net.onelitefeather.vulpes.api.model.font.FontStringEntity;
import net.onelitefeather.vulpes.api.model.project.ProjectEntity;
import net.onelitefeather.vulpes.api.repository.FontRepository;
import org.junit.jupiter.api.Test;
import org.junit.jupiter.api.io.TempDir;

import java.io.IOException;
import java.io.InputStream;
import java.nio.charset.StandardCharsets;
import java.nio.file.Files;
import java.nio.file.Path;
import java.util.ArrayList;
import java.util.LinkedHashMap;
import java.util.Map;
import java.util.List;
import java.util.UUID;

import static org.junit.jupiter.api.Assertions.assertFalse;
import static org.junit.jupiter.api.Assertions.assertThrows;
import static org.junit.jupiter.api.Assertions.assertTrue;
import static org.junit.jupiter.api.Assertions.assertEquals;
import static org.mockito.ArgumentMatchers.any;
import static org.mockito.ArgumentMatchers.eq;
import static org.mockito.Mockito.mock;
import static org.mockito.Mockito.when;

class FontGeneratorTest {

    private static final UUID PROJECT_ID = UUID.fromString("00000000-0000-0000-0000-000000000020");
    private static final String DIRECTORY = "src/autogenerated/java/net/onelitefeather/vulpes/font/";
    private static final String KEYS_PATH = DIRECTORY + "CustomFontSymbolKeys.java";
    private static final String SYMBOLS_PATH = DIRECTORY + "CustomFontSymbols.java";
    private static final String ENTRIES_PATH = DIRECTORY + "CustomFontSymbolEntries.java";
    private static final String FONT_SYMBOL_FIXTURE = "/vulpes-base/net/onelitefeather/vulpes/font/FontSymbol.java";
    private static final String HUD_FILE = "eldoria:font/hud_icons.png";

    @TempDir
    Path tempDir;

    @Test
    void writesPublicNonExtendableKeysInterface() {
        generate(font("hud", "font", HUD_FILE, 7, 8, rows("ab")));

        String code = read(KEYS_PATH);
        assertTrue(code.contains("public interface CustomFontSymbolKeys") && code.contains("@ApiStatus.NonExtendable"),
                "The keys must be a public non extendable interface but was:\n" + code);
    }

    @Test
    void emitsKeyConstantWithFontNamespaceAndSymbolName() {
        generate(font("hud", "font", HUD_FILE, 7, 8, rows("ab")));

        assertTrue(read(KEYS_PATH).contains("Key HUD = Key.key(\"eldoria\", \"hud\");"),
                "The key constant must hold the namespace and the symbol name but was:\n" + read(KEYS_PATH));
    }

    @Test
    void writesPackagePrivateSealedSymbolsInterface() {
        generate(font("hud", "font", HUD_FILE, 7, 8, rows("ab")));

        String code = read(SYMBOLS_PATH);
        assertTrue(code.contains("\nsealed interface CustomFontSymbols permits CustomFontSymbol {"),
                "The symbols must be a package private sealed interface but was:\n" + code);
    }

    @Test
    void emitsSymbolConstantResolvedThroughImpl() {
        generate(font("hud", "font", HUD_FILE, 7, 8, rows("ab")));

        assertTrue(read(SYMBOLS_PATH).contains("CustomFontSymbol HUD = CustomFontSymbolImpl.get(CustomFontSymbolKeys.HUD);"),
                "The constant must be resolved through CustomFontSymbolImpl but was:\n" + read(SYMBOLS_PATH));
    }

    @Test
    void writesPackagePrivateEntriesClassWithPrivateConstructor() {
        generate(font("hud", "font", HUD_FILE, 7, 8, rows("ab")));

        String code = read(ENTRIES_PATH);
        assertTrue(code.contains("\nfinal class CustomFontSymbolEntries {") && code.contains("private CustomFontSymbolEntries()"),
                "The entries must be a final package private class with a private constructor but was:\n" + code);
    }

    @Test
    void emitsEntryWithKeyFontAndFontSymbol() {
        generate(font("hud", "font", HUD_FILE, 7, 8, rows("ab", "cd")));

        assertTrue(read(ENTRIES_PATH).contains("new CustomFontSymbolImpl(CustomFontSymbolKeys.HUD, Key.key(\"eldoria\", \"font\"), "
                        + "new FontSymbol(\"eldoria:font/hud_icons.png\", \"bitmap\", 7, 8, List.of(\"ab\", \"cd\")))"),
                "The entry must hold key, font key and font symbol but was:\n" + read(ENTRIES_PATH));
    }

    @Test
    void doesNotDeclareNestedTypes() {
        generate(font("hud", "font", HUD_FILE, 7, 8, rows("ab")));

        for (String path : List.of(KEYS_PATH, SYMBOLS_PATH, ENTRIES_PATH)) {
            assertFalse(read(path).contains("record Definition"), path + " must not declare a nested Definition");
        }
    }

    @Test
    void sortsConstantsByIdentifierInEveryFile() {
        generate(
                font("zeta", "font", "eldoria:font/zeta.png", 7, 8, rows("z")),
                font("alpha", "font", "eldoria:font/alpha.png", 7, 8, rows("a"))
        );

        for (String path : List.of(KEYS_PATH, SYMBOLS_PATH, ENTRIES_PATH)) {
            String code = read(path);
            assertTrue(code.indexOf("ALPHA") >= 0 && code.indexOf("ALPHA") < code.indexOf("ZETA"),
                    "The constants should be sorted by identifier in " + path + " but was:\n" + code);
        }
    }

    @Test
    void escapesNonAsciiGlyphsAsUnicodeEscapes() {
        generate(font("hud", "font", HUD_FILE, 7, 8, rows("\uE000\u00E4")));

        String code = read(ENTRIES_PATH);
        assertTrue(code.contains("List.of(\"\\uE000\\u00E4\")"),
                "non ASCII glyphs must be written as unicode escapes but was:\n" + code);
        assertFalse(code.contains("\uE000"), "the raw private use glyph must not appear in the source");
    }

    @Test
    void escapesSupplementaryCodepointAsSurrogatePair() {
        generate(font("hud", "font", HUD_FILE, 7, 8, rows(new String(Character.toChars(0x1F600)) + "a")));

        assertTrue(read(ENTRIES_PATH).contains("\"\\uD83D\\uDE00a\""),
                "a supplementary codepoint must be written as a surrogate pair of unicode escapes but was:\n" + read(ENTRIES_PATH));
    }

    @Test
    void escapesQuoteBackslashAndControlCharacters() {
        generate(font("hud", "font", HUD_FILE, 7, 8, rows("\"\\", "\t\n")));

        assertTrue(read(ENTRIES_PATH).contains("List.of(\"\\\"\\\\\", \"\\t\\n\")"),
                "quotes, backslashes and control characters must be escaped but was:\n" + read(ENTRIES_PATH));
    }

    @Test
    void writesEmptyEntriesWithoutFonts() {
        generate();

        for (String path : List.of(KEYS_PATH, SYMBOLS_PATH, ENTRIES_PATH)) {
            assertTrue(Files.exists(tempDir.resolve(path)), "Without fonts " + path + " must still be written");
        }
        assertTrue(read(ENTRIES_PATH).contains("return List.of();"),
                "Without fonts the entries must be an empty list but was:\n" + read(ENTRIES_PATH));
    }

    @Test
    void rejectsFontWithoutCharsWithKeyInMessage() {
        IllegalArgumentException exception = assertThrows(IllegalArgumentException.class,
                () -> generate(font("hud", "font", HUD_FILE, 7, 8, List.of())),
                "a font without chars must abort the generation");

        assertTrue(exception.getMessage().contains("hud"),
                "the message must name the font key but was: " + exception.getMessage());
    }

    @Test
    void rejectsTwoKeysWithSameJavaIdentifierNamingBothKeys() {
        IllegalArgumentException exception = assertThrows(IllegalArgumentException.class,
                () -> generate(font("my-item", "font", HUD_FILE, 7, 8, rows("a")),
                        font("my.item", "font", HUD_FILE, 7, 8, rows("b"))),
                "Two keys that map to the same identifier must abort the generation");

        assertTrue(exception.getMessage().contains("my-item") && exception.getMessage().contains("my.item"),
                "The message must name both keys but was: " + exception.getMessage());
    }

    @Test
    void generatedSourceContainsNoUnresolvedPlaceholders() {
        generate(font("hud", "font", HUD_FILE, 7, 8, rows("ab")));

        for (String path : List.of(KEYS_PATH, SYMBOLS_PATH, ENTRIES_PATH)) {
            assertFalse(read(path).contains("$"), path + " must not contain any unresolved placeholder but was:\n" + read(path));
        }
    }

    @Test
    void generatingTwiceWithSameGeneratorProducesIdenticalSource() {
        FontGenerator generator = new FontGenerator(repositoryWith(
                font("hud", "font", HUD_FILE, 7, 8, rows("ab")),
                font("icons", "font", "eldoria:font/icons.png", 7, 8, rows("cd"))));

        generator.generate(tempDir, PROJECT_ID);
        List<String> first = List.of(read(KEYS_PATH), read(SYMBOLS_PATH), read(ENTRIES_PATH));
        generator.generate(tempDir, PROJECT_ID);

        assertEquals(first, List.of(read(KEYS_PATH), read(SYMBOLS_PATH), read(ENTRIES_PATH)),
                "A second run must not change or duplicate the output");
    }

    @Test
    void generationRunsInReadOnlyTransaction() throws NoSuchMethodException {
        boolean readOnly = FontGenerator.class.getMethod("generate", Path.class, UUID.class).isAnnotationPresent(ReadOnly.class);

        assertTrue(readOnly, "generate must be annotated with @ReadOnly so lazy font chars can be loaded");
    }

    @Test
    void generatedFilesCompileAgainstVulpesBaseStubs() throws IOException {
        generate(
                font("hud", "font", HUD_FILE, 7, 8, rows("\"\\\t", "\u00E4\n\uE000")),
                font("emoji", "symbols", "eldoria:font/emoji.png", 7, 8, rows(new String(Character.toChars(0x1F600)) + "a")),
                font("my-item.v2", "font", HUD_FILE, 7, 8, rows("ab"))
        );
        List<String> sources = new ArrayList<>(writeStubs());
        sources.addAll(List.of(KEYS_PATH, SYMBOLS_PATH, ENTRIES_PATH));

        JavaSourceAssertions.assertCompiles(tempDir, sources.toArray(String[]::new));
    }

    @Test
    void generatedFilesCompileWithoutFonts() throws IOException {
        generate();
        List<String> sources = new ArrayList<>(writeStubs());
        sources.addAll(List.of(KEYS_PATH, SYMBOLS_PATH, ENTRIES_PATH));

        JavaSourceAssertions.assertCompiles(tempDir, sources.toArray(String[]::new));
    }

    /**
     * Writes minimal stand-ins for the hand written vulpes-base types the generated code depends on, and copies the
     * real FontSymbol record of vulpes-base from the test fixtures.
     */
    private List<String> writeStubs() throws IOException {
        Map<String, String> stubs = new LinkedHashMap<>();
        stubs.put("stub/net/onelitefeather/vulpes/VulpesKey.java",
                "package net.onelitefeather.vulpes;\npublic interface VulpesKey { net.kyori.adventure.key.Key key(); }\n");
        stubs.put("stub/net/onelitefeather/vulpes/registry/Registry.java",
                "package net.onelitefeather.vulpes.registry;\npublic interface Registry<T> { }\n");
        stubs.put("stub/net/onelitefeather/vulpes/registry/RegistryFactory.java",
                "package net.onelitefeather.vulpes.registry;\n"
                        + "public final class RegistryFactory {\n"
                        + "    private RegistryFactory() { }\n"
                        + "    public static <T> Registry<T> of(java.util.List<T> entries) { return new Registry<>() { }; }\n"
                        + "}\n");
        stubs.put("stub/net/onelitefeather/vulpes/font/CustomFontSymbol.java",
                "package net.onelitefeather.vulpes.font;\n"
                        + "public sealed interface CustomFontSymbol extends net.onelitefeather.vulpes.VulpesKey, CustomFontSymbols permits CustomFontSymbolImpl {\n"
                        + "    net.kyori.adventure.key.Key font();\n    FontSymbol symbol();\n}\n");
        stubs.put("stub/net/onelitefeather/vulpes/font/CustomFontSymbolImpl.java",
                "package net.onelitefeather.vulpes.font;\n"
                        + "import net.kyori.adventure.key.Key;\n"
                        + "import net.onelitefeather.vulpes.registry.Registry;\n"
                        + "import net.onelitefeather.vulpes.registry.RegistryFactory;\n"
                        + "record CustomFontSymbolImpl(Key key, Key font, FontSymbol symbol) implements CustomFontSymbol {\n"
                        + "    static final Registry<CustomFontSymbol> REGISTRY = RegistryFactory.of(CustomFontSymbolEntries.entries());\n"
                        + "    static CustomFontSymbol get(Key key) { return new CustomFontSymbolImpl(key, key, null); }\n"
                        + "}\n");
        for (Map.Entry<String, String> stub : stubs.entrySet()) {
            Path file = tempDir.resolve(stub.getKey());
            Files.createDirectories(file.getParent());
            Files.writeString(file, stub.getValue(), StandardCharsets.UTF_8);
        }
        List<String> paths = new ArrayList<>(stubs.keySet());
        paths.add(copyFontSymbolFixture());
        return paths;
    }

    private void generate(FontEntity... fonts) {
        new FontGenerator(repositoryWith(fonts)).generate(tempDir, PROJECT_ID);
    }

    private static FontRepository repositoryWith(FontEntity... fonts) {
        FontRepository repository = mock(FontRepository.class);
        when(repository.findByProjectId(eq(PROJECT_ID), any(Pageable.class)))
                .thenReturn(Page.of(List.of(fonts), Pageable.UNPAGED, (long) fonts.length));
        return repository;
    }

    /**
     * Copies the vulpes-base FontSymbol fixture below the test root, so the generated interface compiles against the
     * same record that vulpes-base ships.
     */
    private String copyFontSymbolFixture() throws IOException {
        Path target = tempDir.resolve("fixture/net/onelitefeather/vulpes/font/FontSymbol.java");
        Files.createDirectories(target.getParent());
        try (InputStream in = FontGeneratorTest.class.getResourceAsStream(FONT_SYMBOL_FIXTURE)) {
            assertTrue(in != null, "the FontSymbol fixture must be on the test classpath");
            Files.write(target, in.readAllBytes());
        }
        return "fixture/net/onelitefeather/vulpes/font/FontSymbol.java";
    }

    private String read(String path) {
        try {
            return Files.readString(tempDir.resolve(path), StandardCharsets.UTF_8);
        } catch (IOException e) {
            throw new AssertionError("The file " + path + " should have been generated", e);
        }
    }

    private static List<FontStringEntity> rows(String... lines) {
        List<FontStringEntity> chars = new ArrayList<>();
        for (int i = 0; i < lines.length; i++) {
            chars.add(new FontStringEntity(uuid(i + 1), lines[i], i + 1));
        }
        return chars;
    }

    private static FontEntity font(String key, String mapper, String file, int ascent, int height, List<FontStringEntity> chars) {
        ProjectEntity project = new ProjectEntity();
        project.setKey("eldoria");

        FontEntity font = new FontEntity();
        font.setProject(project);
        font.setKey(key);
        font.setMapper(mapper);
        font.setProvider("bitmap");
        font.setTexturePath(file);
        font.setAscent(ascent);
        font.setHeight(height);
        font.setChars(chars);
        return font;
    }

    private static UUID uuid(int index) {
        return UUID.fromString(String.format("80000000-0000-0000-0000-%012d", index));
    }
}
