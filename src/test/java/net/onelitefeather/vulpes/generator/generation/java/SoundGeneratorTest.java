package net.onelitefeather.vulpes.generator.generation.java;

import io.micronaut.data.model.Page;
import io.micronaut.data.model.Pageable;
import io.micronaut.transaction.annotation.ReadOnly;
import net.onelitefeather.vulpes.api.model.project.ProjectEntity;
import net.onelitefeather.vulpes.api.model.sound.SoundEventEntity;
import net.onelitefeather.vulpes.api.repository.SoundRepository;
import net.onelitefeather.vulpes.generator.generation.JavaSourceAssertions;
import org.junit.jupiter.api.Test;
import org.junit.jupiter.api.io.TempDir;

import java.io.IOException;
import java.nio.file.Files;
import java.nio.file.Path;
import java.util.ArrayList;
import java.util.LinkedHashMap;
import java.util.List;
import java.util.Map;
import java.util.UUID;

import static java.nio.charset.StandardCharsets.UTF_8;
import static org.junit.jupiter.api.Assertions.assertEquals;
import static org.junit.jupiter.api.Assertions.assertFalse;
import static org.junit.jupiter.api.Assertions.assertThrows;
import static org.junit.jupiter.api.Assertions.assertTrue;
import static org.mockito.ArgumentMatchers.any;
import static org.mockito.ArgumentMatchers.eq;
import static org.mockito.Mockito.mock;
import static org.mockito.Mockito.when;

class SoundGeneratorTest {

    private static final UUID PROJECT_ID = UUID.fromString("0f8fad5b-d9cb-469f-a165-70867728950e");
    private static final String DIRECTORY = "src/autogenerated/java/net/onelitefeather/vulpes/sound/";
    private static final String KEYS_PATH = DIRECTORY + "CustomSoundKeys.java";
    private static final String SOUNDS_PATH = DIRECTORY + "CustomSounds.java";
    private static final String ENTRIES_PATH = DIRECTORY + "CustomSoundEntries.java";

    @TempDir
    Path tempDir;

    @Test
    void writesPublicNonExtendableKeysInterface() {
        generate(event("ui_click", "eldoria:ui.click"));

        String code = read(KEYS_PATH);
        assertTrue(code.contains("public interface CustomSoundKeys") && code.contains("@ApiStatus.NonExtendable"),
                "The keys must be a public non extendable interface but was:\n" + code);
    }

    @Test
    void emitsKeyConstantWithNamespaceAndPath() {
        generate(event("ui_click", "eldoria:ui.click"));

        assertTrue(read(KEYS_PATH).contains("Key UI_CLICK = Key.key(\"eldoria\", \"ui.click\");"),
                "The key constant must hold the namespace and the path but was:\n" + read(KEYS_PATH));
    }

    @Test
    void usesProjectNamespaceForKeyNameWithoutNamespace() {
        generate(event("ui_click", "ui.click"));

        assertTrue(read(KEYS_PATH).contains("Key.key(\"eldoria\", \"ui.click\")"),
                "A key name without namespace must use the project namespace but was:\n" + read(KEYS_PATH));
    }

    @Test
    void writesPackagePrivateSealedSoundsInterface() {
        generate(event("ui_click", "eldoria:ui.click"));

        String code = read(SOUNDS_PATH);
        assertTrue(code.contains("\nsealed interface CustomSounds permits CustomSound {"),
                "The sounds must be a package private sealed interface but was:\n" + code);
    }

    @Test
    void emitsSoundConstantResolvedThroughImpl() {
        generate(event("ui_click", "eldoria:ui.click"));

        assertTrue(read(SOUNDS_PATH).contains("CustomSound UI_CLICK = CustomSoundImpl.get(CustomSoundKeys.UI_CLICK);"),
                "The constant must be resolved through CustomSoundImpl but was:\n" + read(SOUNDS_PATH));
    }

    @Test
    void writesPackagePrivateEntriesClassWithPrivateConstructor() {
        generate(event("ui_click", "eldoria:ui.click"));

        String code = read(ENTRIES_PATH);
        assertTrue(code.contains("\nfinal class CustomSoundEntries {") && code.contains("private CustomSoundEntries()"),
                "The entries must be a final package private class with a private constructor but was:\n" + code);
    }

    @Test
    void emitsEntryWithKeyAndNullRange() {
        generate(event("ui_click", "eldoria:ui.click"));

        assertTrue(read(ENTRIES_PATH).contains("new CustomSoundImpl(CustomSoundKeys.UI_CLICK, null)"),
                "The entry must hold the key and a null range but was:\n" + read(ENTRIES_PATH));
    }

    @Test
    void doesNotDeclareNestedTypes() {
        generate(event("ui_click", "eldoria:ui.click"));

        for (String path : List.of(KEYS_PATH, SOUNDS_PATH, ENTRIES_PATH)) {
            assertFalse(read(path).contains("record Definition"), path + " must not declare a nested Definition");
        }
    }

    @Test
    void sortsConstantsByIdentifierInEveryFile() {
        generate(
                event("zeta", "eldoria:zeta.sound"),
                event("alpha", "eldoria:alpha.sound"),
                event("mid", "eldoria:mid.sound")
        );

        for (String path : List.of(KEYS_PATH, SOUNDS_PATH, ENTRIES_PATH)) {
            String code = read(path);
            int alpha = code.indexOf("ALPHA");
            int mid = code.indexOf("MID");
            int zeta = code.indexOf("ZETA");
            assertTrue(alpha >= 0 && alpha < mid && mid < zeta,
                    "The constants should be sorted by identifier in " + path + " but was:\n" + code);
        }
    }

    @Test
    void writesEmptyEntriesWithoutSounds() {
        generate();

        for (String path : List.of(KEYS_PATH, SOUNDS_PATH, ENTRIES_PATH)) {
            assertTrue(Files.exists(tempDir.resolve(path)), "Without sounds " + path + " must still be written");
        }
        assertTrue(read(ENTRIES_PATH).contains("return List.of();"),
                "Without sounds the entries must be an empty list but was:\n" + read(ENTRIES_PATH));
    }

    @Test
    void rejectsInvalidKeyWithKeyNameInMessage() {
        IllegalArgumentException exception = assertThrows(IllegalArgumentException.class,
                () -> generate(event("broken", "eldoria:Ui Click")),
                "An invalid sound key must abort the generation");

        assertTrue(exception.getMessage().contains("eldoria:Ui Click"),
                "The message should name the invalid key but was: " + exception.getMessage());
    }

    @Test
    void rejectsTwoKeysWithSameJavaIdentifierNamingBothKeys() {
        IllegalArgumentException exception = assertThrows(IllegalArgumentException.class,
                () -> generate(event("my-item", "eldoria:a"), event("my.item", "eldoria:b")),
                "Two variable names that map to the same identifier must abort the generation");

        assertTrue(exception.getMessage().contains("my-item") && exception.getMessage().contains("my.item"),
                "The message must name both keys but was: " + exception.getMessage());
    }

    @Test
    void generationRunsInReadOnlyTransaction() throws NoSuchMethodException {
        boolean readOnly = SoundGenerator.class.getMethod("generate", Path.class, UUID.class).isAnnotationPresent(ReadOnly.class);

        assertTrue(readOnly, "generate must be annotated with @ReadOnly so lazy sound data can be loaded");
    }

    @Test
    void generatingTwiceOnTheSameInstanceProducesIdenticalSource() {
        SoundGenerator generator = generatorWith(event("ui_click", "eldoria:ui.click"), event("alpha", "eldoria:alpha.sound"));

        generator.generate(tempDir, PROJECT_ID);
        List<String> first = List.of(read(KEYS_PATH), read(SOUNDS_PATH), read(ENTRIES_PATH));
        generator.generate(tempDir, PROJECT_ID);

        assertEquals(first, List.of(read(KEYS_PATH), read(SOUNDS_PATH), read(ENTRIES_PATH)),
                "A second run must not change or duplicate the output");
    }

    @Test
    void generatedFilesCompileAgainstVulpesBaseStubs() throws IOException {
        generate(event("ui_click", "eldoria:ui.click"), event("my-item.v2", "minigames:my-item.v2"));

        JavaSourceAssertions.assertCompiles(tempDir, sourcesWithStubs());
    }

    @Test
    void generatedFilesCompileWithoutSounds() throws IOException {
        generate();

        JavaSourceAssertions.assertCompiles(tempDir, sourcesWithStubs());
    }

    private String[] sourcesWithStubs() throws IOException {
        List<String> sources = new ArrayList<>(writeStubs());
        sources.addAll(List.of(KEYS_PATH, SOUNDS_PATH, ENTRIES_PATH));
        return sources.toArray(String[]::new);
    }

    /**
     * Writes minimal stand-ins for the hand written vulpes-base types the generated code depends on.
     */
    private List<String> writeStubs() throws IOException {
        Map<String, String> stubs = new LinkedHashMap<>();
        stubs.put("stub/net/onelitefeather/vulpes/VulpesKey.java",
                "package net.onelitefeather.vulpes;\npublic interface VulpesKey { net.kyori.adventure.key.Key key(); }\n");
        stubs.put("stub/net/onelitefeather/vulpes/registry/Registry.java",
                "package net.onelitefeather.vulpes.registry;\npublic interface Registry<T> { }\n");
        stubs.put("stub/net/onelitefeather/vulpes/registry/RegistryFactory.java",
                "package net.onelitefeather.vulpes.registry;\n"
                        + "public final class RegistryFactory {\n"
                        + "    private RegistryFactory() { }\n"
                        + "    public static <T> Registry<T> of(java.util.List<T> entries) { return new Registry<>() { }; }\n"
                        + "}\n");
        stubs.put("stub/net/onelitefeather/vulpes/sound/CustomSound.java",
                "package net.onelitefeather.vulpes.sound;\n"
                        + "public sealed interface CustomSound extends net.onelitefeather.vulpes.VulpesKey, CustomSounds permits CustomSoundImpl {\n"
                        + "    Float range();\n    net.minestom.server.sound.SoundEvent soundEvent();\n}\n");
        stubs.put("stub/net/onelitefeather/vulpes/sound/CustomSoundImpl.java",
                "package net.onelitefeather.vulpes.sound;\n"
                        + "import net.kyori.adventure.key.Key;\n"
                        + "import net.onelitefeather.vulpes.registry.Registry;\n"
                        + "import net.onelitefeather.vulpes.registry.RegistryFactory;\n"
                        + "record CustomSoundImpl(Key key, Float range) implements CustomSound {\n"
                        + "    static final Registry<CustomSound> REGISTRY = RegistryFactory.of(CustomSoundEntries.entries());\n"
                        + "    public net.minestom.server.sound.SoundEvent soundEvent() { return net.minestom.server.sound.SoundEvent.of(key.asString(), range); }\n"
                        + "    static CustomSound get(Key key) { return new CustomSoundImpl(key, null); }\n"
                        + "}\n");
        for (Map.Entry<String, String> stub : stubs.entrySet()) {
            Path file = tempDir.resolve(stub.getKey());
            Files.createDirectories(file.getParent());
            Files.writeString(file, stub.getValue(), UTF_8);
        }
        return new ArrayList<>(stubs.keySet());
    }

    private SoundGenerator generatorWith(SoundEventEntity... events) {
        SoundRepository repository = mock(SoundRepository.class);
        when(repository.findByProjectId(eq(PROJECT_ID), any(Pageable.class)))
                .thenReturn(Page.of(List.of(events), Pageable.UNPAGED, (long) events.length));
        return new SoundGenerator(repository);
    }

    private void generate(SoundEventEntity... events) {
        generatorWith(events).generate(tempDir, PROJECT_ID);
    }

    private String read(String path) {
        try {
            return Files.readString(tempDir.resolve(path), UTF_8);
        } catch (IOException e) {
            throw new AssertionError("The file " + path + " should have been generated", e);
        }
    }

    private static SoundEventEntity event(String key, String keyName) {
        ProjectEntity project = new ProjectEntity();
        project.setKey("eldoria");
        return new SoundEventEntity(
                UUID.nameUUIDFromBytes(key.getBytes(UTF_8)),
                key,
                key,
                keyName,
                false,
                null,
                null,
                List.of(),
                project
        );
    }
}
