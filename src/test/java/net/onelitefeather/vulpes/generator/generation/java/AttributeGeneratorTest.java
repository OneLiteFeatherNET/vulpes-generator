package net.onelitefeather.vulpes.generator.generation.java;

import io.micronaut.data.model.Page;
import io.micronaut.data.model.Pageable;
import net.onelitefeather.vulpes.api.model.AttributeEntity;
import net.onelitefeather.vulpes.api.model.project.ProjectEntity;
import net.onelitefeather.vulpes.api.repository.AttributeRepository;
import net.onelitefeather.vulpes.generator.generation.JavaSourceAssertions;
import org.junit.jupiter.api.Test;
import org.junit.jupiter.api.io.TempDir;

import java.io.IOException;
import java.nio.file.Files;
import java.nio.file.Path;
import java.util.ArrayList;
import java.util.LinkedHashMap;
import java.util.List;
import java.util.Map;
import java.util.UUID;

import static java.nio.charset.StandardCharsets.UTF_8;
import static org.junit.jupiter.api.Assertions.assertEquals;
import static org.junit.jupiter.api.Assertions.assertFalse;
import static org.junit.jupiter.api.Assertions.assertThrows;
import static org.junit.jupiter.api.Assertions.assertTrue;
import static org.mockito.ArgumentMatchers.any;
import static org.mockito.ArgumentMatchers.eq;
import static org.mockito.Mockito.mock;
import static org.mockito.Mockito.when;

class AttributeGeneratorTest {

    private static final UUID PROJECT_ID = UUID.fromString("00000000-0000-0000-0000-000000000001");
    private static final UUID ENTITY_ID = UUID.fromString("00000000-0000-0000-0000-000000000002");
    private static final String PROJECT_KEY = "eldoria_rpg";
    private static final String DIRECTORY = "src/autogenerated/java/net/onelitefeather/vulpes/attribute/";
    private static final String KEYS_PATH = DIRECTORY + "CustomAttributeKeys.java";
    private static final String ATTRIBUTES_PATH = DIRECTORY + "CustomAttributes.java";
    private static final String ENTRIES_PATH = DIRECTORY + "CustomAttributeEntries.java";

    @TempDir
    Path tempDir;

    @Test
    void writesPublicNonExtendableKeysInterface() {
        generate(attribute("crit_chance", "Critical Hit Chance", 0.05, 1.0));

        String code = read(KEYS_PATH);
        assertTrue(code.contains("public interface CustomAttributeKeys") && code.contains("@ApiStatus.NonExtendable"),
                "The keys must be a public non extendable interface but was:\n" + code);
    }

    @Test
    void emitsKeyConstantWithNamespaceAndPath() {
        generate(attribute("crit_chance", "Critical Hit Chance", 0.05, 1.0));

        assertTrue(read(KEYS_PATH).contains("Key CRIT_CHANCE = Key.key(\"eldoria_rpg\", \"crit_chance\");"),
                "The key constant must hold the namespace and the path but was:\n" + read(KEYS_PATH));
    }

    @Test
    void writesPackagePrivateSealedAttributesInterface() {
        generate(attribute("crit_chance", "Critical Hit Chance", 0.05, 1.0));

        String code = read(ATTRIBUTES_PATH);
        assertTrue(code.contains("\nsealed interface CustomAttributes permits CustomAttribute {"),
                "The attributes must be a package private sealed interface but was:\n" + code);
    }

    @Test
    void emitsAttributeConstantResolvedThroughImpl() {
        generate(attribute("crit_chance", "Critical Hit Chance", 0.05, 1.0));

        assertTrue(read(ATTRIBUTES_PATH).contains(
                        "CustomAttribute CRIT_CHANCE = CustomAttributeImpl.get(CustomAttributeKeys.CRIT_CHANCE);"),
                "The constant must be resolved through CustomAttributeImpl but was:\n" + read(ATTRIBUTES_PATH));
    }

    @Test
    void writesPackagePrivateEntriesClassWithPrivateConstructor() {
        generate(attribute("crit_chance", "Critical Hit Chance", 0.05, 1.0));

        String code = read(ENTRIES_PATH);
        assertTrue(code.contains("\nfinal class CustomAttributeEntries {") && code.contains("private CustomAttributeEntries()"),
                "The entries must be a final package private class with a private constructor but was:\n" + code);
    }

    @Test
    void emitsEntryWithKeyUiNameAndDoubleValues() {
        generate(attribute("crit_chance", "Critical Hit Chance", 0.05, 1.0));

        assertTrue(read(ENTRIES_PATH).contains(
                        "new CustomAttributeImpl(CustomAttributeKeys.CRIT_CHANCE, \"Critical Hit Chance\", 0.05, 1.0)"),
                "The entry must hold the key, the ui name and the double values but was:\n" + read(ENTRIES_PATH));
    }

    @Test
    void escapesQuotesInUiName() {
        generate(attribute("crit_chance", "Crit \"Chance\"", 0.05, 1.0));

        assertTrue(read(ENTRIES_PATH).contains("\"Crit \\\"Chance\\\"\""),
                "Quotes in the ui name must be escaped but was:\n" + read(ENTRIES_PATH));
    }

    @Test
    void doesNotDeclareNestedTypes() {
        generate(attribute("crit_chance", "Critical Hit Chance", 0.05, 1.0));

        for (String path : List.of(KEYS_PATH, ATTRIBUTES_PATH, ENTRIES_PATH)) {
            assertFalse(read(path).contains("record Definition"), path + " must not declare a nested Definition");
        }
    }

    @Test
    void sortsConstantsByIdentifierInEveryFile() {
        generate(
                attribute("zeta", "Zeta", 0.0, 1.0),
                attribute("alpha", "Alpha", 0.0, 1.0)
        );

        for (String path : List.of(KEYS_PATH, ATTRIBUTES_PATH, ENTRIES_PATH)) {
            String code = read(path);
            assertTrue(code.indexOf("ALPHA") >= 0 && code.indexOf("ALPHA") < code.indexOf("ZETA"),
                    "The constants should be sorted by identifier in " + path + " but was:\n" + code);
        }
    }

    @Test
    void writesEmptyEntriesWithoutAttributes() {
        generate();

        for (String path : List.of(KEYS_PATH, ATTRIBUTES_PATH, ENTRIES_PATH)) {
            assertTrue(Files.exists(tempDir.resolve(path)), "Without attributes " + path + " must still be written");
        }
        assertTrue(read(ENTRIES_PATH).contains("return List.of();"),
                "Without attributes the entries must be an empty list but was:\n" + read(ENTRIES_PATH));
    }

    @Test
    void rejectsMaximumBelowDefaultWithKeyInMessage() {
        IllegalArgumentException exception = assertThrows(IllegalArgumentException.class,
                () -> generate(attribute("crit_chance", "Critical Hit Chance", 2.0, 1.0)),
                "A maximum below the default must abort the generation");

        assertTrue(exception.getMessage().contains("crit_chance"),
                "The message must name the attribute key but was: " + exception.getMessage());
    }

    @Test
    void rejectsNonFiniteValueWithKeyInMessage() {
        IllegalArgumentException exception = assertThrows(IllegalArgumentException.class,
                () -> generate(attribute("crit_chance", "Critical Hit Chance", Double.NaN, 1.0)),
                "A NaN default value must abort the generation");

        assertTrue(exception.getMessage().contains("crit_chance"),
                "The message must name the attribute key but was: " + exception.getMessage());
    }

    @Test
    void rejectsBlankUiNameWithKeyInMessage() {
        IllegalArgumentException exception = assertThrows(IllegalArgumentException.class,
                () -> generate(attribute("crit_chance", " ", 0.05, 1.0)),
                "A blank ui name must abort the generation");

        assertTrue(exception.getMessage().contains("crit_chance"),
                "The message must name the attribute key but was: " + exception.getMessage());
    }

    @Test
    void rejectsTwoKeysWithSameJavaIdentifierNamingBothKeys() {
        IllegalArgumentException exception = assertThrows(IllegalArgumentException.class,
                () -> generate(attribute("my-item", "Item", 0.0, 1.0), attribute("my.item", "Item", 0.0, 1.0)),
                "Two keys that map to the same identifier must abort the generation");

        assertTrue(exception.getMessage().contains("my-item") && exception.getMessage().contains("my.item"),
                "The message must name both keys but was: " + exception.getMessage());
    }

    @Test
    void generatingTwiceWithSameGeneratorProducesIdenticalSource() {
        AttributeGenerator generator = new AttributeGenerator(repositoryWith(
                attribute("crit_chance", "Critical Hit Chance", 0.05, 1.0),
                attribute("mana_regen", "Mana Regeneration", 0.0, 10.0)));

        generator.generate(tempDir, PROJECT_ID);
        List<String> first = List.of(read(KEYS_PATH), read(ATTRIBUTES_PATH), read(ENTRIES_PATH));
        generator.generate(tempDir, PROJECT_ID);

        assertEquals(first, List.of(read(KEYS_PATH), read(ATTRIBUTES_PATH), read(ENTRIES_PATH)),
                "A second run must not change or duplicate the output");
    }

    @Test
    void generatedFilesCompileAgainstVulpesBaseStubs() throws IOException {
        generate(attribute("crit_chance", "Critical Hit Chance", 0.05, 1.0),
                attribute("mana_regen", "Mana \"Regeneration\"", 0.0, 10.0));
        List<String> stubs = writeStubs();
        List<String> sources = new ArrayList<>(stubs);
        sources.addAll(List.of(KEYS_PATH, ATTRIBUTES_PATH, ENTRIES_PATH));

        JavaSourceAssertions.assertCompiles(tempDir, sources.toArray(String[]::new));
    }

    @Test
    void generatedFilesCompileWithoutAttributes() throws IOException {
        generate();
        List<String> sources = new ArrayList<>(writeStubs());
        sources.addAll(List.of(KEYS_PATH, ATTRIBUTES_PATH, ENTRIES_PATH));

        JavaSourceAssertions.assertCompiles(tempDir, sources.toArray(String[]::new));
    }

    /**
     * Writes minimal stand-ins for the hand written vulpes-base types the generated code depends on.
     */
    private List<String> writeStubs() throws IOException {
        Map<String, String> stubs = new LinkedHashMap<>();
        stubs.put("stub/net/onelitefeather/vulpes/VulpesKey.java",
                "package net.onelitefeather.vulpes;\npublic interface VulpesKey { net.kyori.adventure.key.Key key(); }\n");
        stubs.put("stub/net/onelitefeather/vulpes/registry/Registry.java",
                "package net.onelitefeather.vulpes.registry;\npublic interface Registry<T> { }\n");
        stubs.put("stub/net/onelitefeather/vulpes/registry/RegistryFactory.java",
                "package net.onelitefeather.vulpes.registry;\n"
                        + "public final class RegistryFactory {\n"
                        + "    private RegistryFactory() { }\n"
                        + "    public static <T> Registry<T> of(java.util.List<T> entries) { return new Registry<>() { }; }\n"
                        + "}\n");
        stubs.put("stub/net/onelitefeather/vulpes/attribute/CustomAttribute.java",
                "package net.onelitefeather.vulpes.attribute;\n"
                        + "public sealed interface CustomAttribute extends net.onelitefeather.vulpes.VulpesKey, CustomAttributes permits CustomAttributeImpl {\n"
                        + "    String displayName();\n    double defaultValue();\n    double maximumValue();\n}\n");
        stubs.put("stub/net/onelitefeather/vulpes/attribute/CustomAttributeImpl.java",
                "package net.onelitefeather.vulpes.attribute;\n"
                        + "import net.kyori.adventure.key.Key;\n"
                        + "import net.onelitefeather.vulpes.registry.Registry;\n"
                        + "import net.onelitefeather.vulpes.registry.RegistryFactory;\n"
                        + "record CustomAttributeImpl(Key key, String displayName, double defaultValue, double maximumValue) implements CustomAttribute {\n"
                        + "    static final Registry<CustomAttribute> REGISTRY = RegistryFactory.of(CustomAttributeEntries.entries());\n"
                        + "    static CustomAttribute get(Key key) { return new CustomAttributeImpl(key, key.value(), 0, 0); }\n"
                        + "}\n");
        for (Map.Entry<String, String> stub : stubs.entrySet()) {
            Path file = tempDir.resolve(stub.getKey());
            Files.createDirectories(file.getParent());
            Files.writeString(file, stub.getValue(), UTF_8);
        }
        return new ArrayList<>(stubs.keySet());
    }

    private void generate(AttributeEntity... attributes) {
        new AttributeGenerator(repositoryWith(attributes)).generate(tempDir, PROJECT_ID);
    }

    private static AttributeRepository repositoryWith(AttributeEntity... attributes) {
        AttributeRepository repository = mock(AttributeRepository.class);
        when(repository.findByProjectId(eq(PROJECT_ID), any(Pageable.class)))
                .thenReturn(Page.of(List.of(attributes), Pageable.UNPAGED, (long) attributes.length));
        return repository;
    }

    private String read(String path) {
        try {
            return Files.readString(tempDir.resolve(path), UTF_8);
        } catch (IOException e) {
            throw new AssertionError("The file " + path + " should have been generated", e);
        }
    }

    private static AttributeEntity attribute(String key, String uiName, double defaultValue, double maximumValue) {
        ProjectEntity project = new ProjectEntity();
        project.setKey(PROJECT_KEY);
        return new AttributeEntity(ENTITY_ID, uiName, key, defaultValue, maximumValue, project);
    }
}
