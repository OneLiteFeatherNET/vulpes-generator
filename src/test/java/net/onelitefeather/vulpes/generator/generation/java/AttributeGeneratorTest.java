package net.onelitefeather.vulpes.generator.generation.java;

import io.micronaut.data.model.Page;
import io.micronaut.data.model.Pageable;
import net.onelitefeather.vulpes.api.model.AttributeEntity;
import net.onelitefeather.vulpes.api.model.project.ProjectEntity;
import net.onelitefeather.vulpes.api.repository.AttributeRepository;
import net.onelitefeather.vulpes.generator.generation.JavaSourceAssertions;
import org.junit.jupiter.api.Test;
import org.junit.jupiter.api.io.TempDir;

import java.io.IOException;
import java.nio.file.Files;
import java.nio.file.Path;
import java.util.List;
import java.util.UUID;

import static java.nio.charset.StandardCharsets.UTF_8;
import static org.junit.jupiter.api.Assertions.assertEquals;
import static org.junit.jupiter.api.Assertions.assertFalse;
import static org.junit.jupiter.api.Assertions.assertThrows;
import static org.junit.jupiter.api.Assertions.assertTrue;
import static org.mockito.ArgumentMatchers.any;
import static org.mockito.ArgumentMatchers.eq;
import static org.mockito.Mockito.mock;
import static org.mockito.Mockito.when;

class AttributeGeneratorTest {

    private static final UUID PROJECT_ID = UUID.fromString("00000000-0000-0000-0000-000000000001");
    private static final UUID ENTITY_ID = UUID.fromString("00000000-0000-0000-0000-000000000002");
    private static final String PROJECT_KEY = "eldoria_rpg";
    private static final String INTERFACE_PATH = "src/autogenerated/java/net/onelitefeather/vulpes/attribute/CustomAttributes.java";

    @TempDir
    Path tempDir;

    @Test
    void writesPublicInterfaceNamedCustomAttributes() {
        generate(attribute("crit_chance", "Critical Hit Chance", 0.05, 1.0));

        assertTrue(readInterface().contains("public interface CustomAttributes"),
                "The attributes must be generated as public interface CustomAttributes but was:\n" + readInterface());
    }

    @Test
    void emitsDefinitionWithNamespacedKeyUiNameAndDoubleValues() {
        generate(attribute("crit_chance", "Critical Hit Chance", 0.05, 1.0));

        assertTrue(readInterface().contains(
                        "CRIT_CHANCE = new Definition(Key.key(\"eldoria_rpg\", \"crit_chance\"), \"Critical Hit Chance\", 0.05, 1.0);"),
                "The constant must hold the namespaced key, the ui name and the double values but was:\n" + readInterface());
    }

    @Test
    void declaresNestedDefinitionRecord() {
        generate(attribute("crit_chance", "Critical Hit Chance", 0.05, 1.0));

        assertTrue(readInterface().contains(
                        "record Definition(net.kyori.adventure.key.Key key, String name, double defaultValue, double maximumValue)"),
                "The interface must declare the nested record Definition but was:\n" + readInterface());
    }

    @Test
    void sortsConstantsByIdentifier() {
        generate(
                attribute("zeta", "Zeta", 0.0, 1.0),
                attribute("alpha", "Alpha", 0.0, 1.0)
        );

        String code = readInterface();
        assertTrue(code.indexOf("ALPHA =") >= 0 && code.indexOf("ALPHA =") < code.indexOf("ZETA ="),
                "The constants should be sorted by identifier but was:\n" + code);
    }

    @Test
    void writesEmptyInterfaceWithoutAttributes() {
        generate();

        assertTrue(Files.exists(tempDir.resolve(INTERFACE_PATH)),
                "Without attributes the empty interface must still be written so the placeholder is replaced");
        assertFalse(readInterface().contains(" = new Definition("),
                "Without attributes no constant must be emitted but was:\n" + readInterface());
    }

    @Test
    void rejectsMaximumBelowDefaultWithKeyInMessage() {
        IllegalArgumentException exception = assertThrows(IllegalArgumentException.class,
                () -> generate(attribute("crit_chance", "Critical Hit Chance", 2.0, 1.0)),
                "A maximum below the default must abort the generation");

        assertTrue(exception.getMessage().contains("crit_chance"),
                "The message must name the attribute key but was: " + exception.getMessage());
    }

    @Test
    void rejectsNonFiniteValueWithKeyInMessage() {
        IllegalArgumentException exception = assertThrows(IllegalArgumentException.class,
                () -> generate(attribute("crit_chance", "Critical Hit Chance", Double.NaN, 1.0)),
                "A NaN default value must abort the generation");

        assertTrue(exception.getMessage().contains("crit_chance"),
                "The message must name the attribute key but was: " + exception.getMessage());
    }

    @Test
    void rejectsBlankUiNameWithKeyInMessage() {
        IllegalArgumentException exception = assertThrows(IllegalArgumentException.class,
                () -> generate(attribute("crit_chance", " ", 0.05, 1.0)),
                "A blank ui name must abort the generation");

        assertTrue(exception.getMessage().contains("crit_chance"),
                "The message must name the attribute key but was: " + exception.getMessage());
    }

    @Test
    void rejectsTwoKeysWithSameJavaIdentifierNamingBothKeys() {
        IllegalArgumentException exception = assertThrows(IllegalArgumentException.class,
                () -> generate(attribute("my-item", "Item", 0.0, 1.0), attribute("my.item", "Item", 0.0, 1.0)),
                "Two keys that map to the same identifier must abort the generation");

        assertTrue(exception.getMessage().contains("my-item") && exception.getMessage().contains("my.item"),
                "The message must name both keys but was: " + exception.getMessage());
    }

    @Test
    void generatingTwiceWithSameGeneratorProducesIdenticalSource() {
        AttributeGenerator generator = new AttributeGenerator(repositoryWith(
                attribute("crit_chance", "Critical Hit Chance", 0.05, 1.0),
                attribute("mana_regen", "Mana Regeneration", 0.0, 10.0)));

        generator.generate(tempDir, PROJECT_ID);
        String first = readInterface();
        generator.generate(tempDir, PROJECT_ID);

        assertEquals(first, readInterface(), "A second run must not add fields or annotations again");
    }

    @Test
    void generatedInterfaceCompiles() throws IOException {
        generate(attribute("crit_chance", "Critical Hit Chance", 0.05, 1.0));

        JavaSourceAssertions.assertCompiles(tempDir, INTERFACE_PATH);
    }

    private void generate(AttributeEntity... attributes) {
        new AttributeGenerator(repositoryWith(attributes)).generate(tempDir, PROJECT_ID);
    }

    private static AttributeRepository repositoryWith(AttributeEntity... attributes) {
        AttributeRepository repository = mock(AttributeRepository.class);
        when(repository.findByProjectId(eq(PROJECT_ID), any(Pageable.class)))
                .thenReturn(Page.of(List.of(attributes), Pageable.UNPAGED, (long) attributes.length));
        return repository;
    }

    private String readInterface() {
        try {
            return Files.readString(tempDir.resolve(INTERFACE_PATH), UTF_8);
        } catch (IOException e) {
            throw new AssertionError("The CustomAttributes interface should have been generated at " + INTERFACE_PATH, e);
        }
    }

    private static AttributeEntity attribute(String key, String uiName, double defaultValue, double maximumValue) {
        ProjectEntity project = new ProjectEntity();
        project.setKey(PROJECT_KEY);
        return new AttributeEntity(ENTITY_ID, uiName, key, defaultValue, maximumValue, project);
    }
}
