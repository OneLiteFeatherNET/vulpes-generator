package net.onelitefeather.vulpes.generator.generation.java;

import io.micronaut.data.model.Page;
import io.micronaut.data.model.Pageable;
import io.micronaut.transaction.annotation.ReadOnly;
import net.onelitefeather.vulpes.api.model.advancement.AdvancementEntity;
import net.onelitefeather.vulpes.api.model.advancement.AdvancementFrameType;
import net.onelitefeather.vulpes.api.model.project.ProjectEntity;
import net.onelitefeather.vulpes.api.repository.AdvancementRepository;
import net.onelitefeather.vulpes.generator.generation.JavaSourceAssertions;
import org.junit.jupiter.api.BeforeEach;
import org.junit.jupiter.api.Test;
import org.junit.jupiter.api.io.TempDir;

import java.io.IOException;
import java.nio.file.Files;
import java.nio.file.Path;
import java.util.ArrayList;
import java.util.LinkedHashMap;
import java.util.List;
import java.util.Map;
import java.util.UUID;

import static java.nio.charset.StandardCharsets.UTF_8;
import static org.junit.jupiter.api.Assertions.assertEquals;
import static org.junit.jupiter.api.Assertions.assertFalse;
import static org.junit.jupiter.api.Assertions.assertThrows;
import static org.junit.jupiter.api.Assertions.assertTrue;
import static org.mockito.ArgumentMatchers.any;
import static org.mockito.ArgumentMatchers.eq;
import static org.mockito.Mockito.mock;
import static org.mockito.Mockito.when;

class AdvancementGeneratorTest {

    private static final UUID PROJECT_ID = UUID.fromString("0f8fad5b-d9cb-469f-a165-70867728950e");
    private static final String STONE_BACKGROUND = "minecraft:textures/gui/advancements/backgrounds/stone.png";
    private static final String DIRECTORY = "src/autogenerated/java/net/onelitefeather/vulpes/advancement/";
    private static final String KEYS_PATH = DIRECTORY + "CustomAdvancementKeys.java";
    private static final String ADVANCEMENTS_PATH = DIRECTORY + "CustomAdvancements.java";
    private static final String ENTRIES_PATH = DIRECTORY + "CustomAdvancementEntries.java";
    private static final List<String> ALL_PATHS = List.of(KEYS_PATH, ADVANCEMENTS_PATH, ENTRIES_PATH);

    @TempDir
    Path tempDir;

    private AdvancementRepository repository;
    private ProjectEntity project;

    @BeforeEach
    void setUp() {
        repository = mock(AdvancementRepository.class);
        project = new ProjectEntity();
        project.setKey("vulpes");
    }

    @Test
    void writesPublicNonExtendableKeysInterface() {
        generate(advancement("root", null));

        String code = read(KEYS_PATH);
        assertTrue(code.contains("public interface CustomAdvancementKeys") && code.contains("@ApiStatus.NonExtendable"),
                "The keys must be a public non extendable interface but was:\n" + code);
    }

    @Test
    void emitsKeyConstantWithNamespaceAndPath() {
        generate(advancement("root", null));

        assertTrue(read(KEYS_PATH).contains("Key ROOT = Key.key(\"vulpes\", \"root\");"),
                "The key constant must hold the namespace and the path but was:\n" + read(KEYS_PATH));
    }

    @Test
    void writesPackagePrivateSealedAdvancementsInterface() {
        generate(advancement("root", null));

        String code = read(ADVANCEMENTS_PATH);
        assertTrue(code.contains("\nsealed interface CustomAdvancements permits CustomAdvancement {"),
                "The advancements must be a package private sealed interface but was:\n" + code);
    }

    @Test
    void emitsAdvancementConstantResolvedThroughImpl() {
        generate(advancement("root", null));

        assertTrue(read(ADVANCEMENTS_PATH).contains("CustomAdvancement ROOT = CustomAdvancementImpl.get(CustomAdvancementKeys.ROOT);"),
                "The constant must be resolved through CustomAdvancementImpl but was:\n" + read(ADVANCEMENTS_PATH));
    }

    @Test
    void writesPackagePrivateEntriesClassWithPrivateConstructor() {
        generate(advancement("root", null));

        String code = read(ENTRIES_PATH);
        assertTrue(code.contains("\nfinal class CustomAdvancementEntries {") && code.contains("private CustomAdvancementEntries()"),
                "The entries must be a final package private class with a private constructor but was:\n" + code);
    }

    @Test
    void rootEntryHasNullParent() {
        generate(advancement("root", null));

        assertTrue(read(ENTRIES_PATH).contains("new CustomAdvancementImpl(CustomAdvancementKeys.ROOT, null, "),
                "A root must have a null parent but was:\n" + read(ENTRIES_PATH));
    }

    @Test
    void childEntryReferencesParentKeyConstant() {
        AdvancementEntity root = advancement("root", null);

        generate(root, advancement("child", root));

        assertTrue(read(ENTRIES_PATH).contains("new CustomAdvancementImpl(CustomAdvancementKeys.CHILD, CustomAdvancementKeys.ROOT, "),
                "A child must reference the key constant of its parent but was:\n" + read(ENTRIES_PATH));
    }

    @Test
    void doesNotDeclareNestedTypesOrTabCode() {
        AdvancementEntity root = advancement("root", null);

        generate(root, advancement("child", root));

        for (String path : ALL_PATHS) {
            String code = read(path);
            assertFalse(code.contains("record ") || code.contains("AdvancementManager") || code.contains("createTab"),
                    path + " must only contain definitions but was:\n" + code);
        }
    }

    @Test
    void sortsConstantsByIdentifierInEveryFile() {
        generate(advancement("zeta", null), advancement("alpha", null));

        for (String path : ALL_PATHS) {
            String code = read(path);
            assertTrue(code.indexOf("ALPHA") >= 0 && code.indexOf("ALPHA") < code.indexOf("ZETA"),
                    "The constants should be sorted by identifier in " + path + " but was:\n" + code);
        }
    }

    @Test
    void writesEmptyEntriesWithoutAdvancements() {
        generate();

        for (String path : ALL_PATHS) {
            assertTrue(Files.exists(tempDir.resolve(path)), "Without advancements " + path + " must still be written");
        }
        assertTrue(read(ENTRIES_PATH).contains("return List.of();"),
                "Without advancements the entries must be an empty list but was:\n" + read(ENTRIES_PATH));
    }

    @Test
    void resolvesLegacyMaterialStoneToStone() {
        AdvancementEntity root = advancement("root", null);
        root.setMaterial("STONE");

        generate(root);

        assertTrue(read(ENTRIES_PATH).contains("ItemStack.of(Material.STONE)"),
                "The legacy material STONE should resolve to Material.STONE but was:\n" + read(ENTRIES_PATH));
    }

    @Test
    void missingMaterialFallsBackToPaper() {
        AdvancementEntity root = advancement("root", null);
        root.setMaterial(null);

        generate(root);

        assertTrue(read(ENTRIES_PATH).contains("Material.PAPER"),
                "A missing material should fall back to Material.PAPER but was:\n" + read(ENTRIES_PATH));
    }

    @Test
    void titleIsDeserializedWithGsonComponentSerializer() {
        AdvancementEntity root = advancement("root", null);
        root.setTitle("{\"text\":\"Title\"}");

        generate(root);

        assertTrue(read(ENTRIES_PATH).contains("GsonComponentSerializer.gson().deserialize(\"{\\\"text\\\":\\\"Title\\\"}\")"),
                "The title should be deserialized from its JSON text but was:\n" + read(ENTRIES_PATH));
    }

    @Test
    void titleAsJsonStringLiteralIsAccepted() {
        AdvancementEntity root = advancement("root", null);
        root.setTitle("\"Title\"");

        generate(root);

        assertTrue(read(ENTRIES_PATH).contains("GsonComponentSerializer.gson().deserialize(\"\\\"Title\\\"\")"),
                "A title given as JSON string literal should be accepted but was:\n" + read(ENTRIES_PATH));
    }

    @Test
    void missingDescriptionUsesEmptyComponent() {
        AdvancementEntity root = advancement("root", null);
        root.setDescription(null);

        generate(root);

        assertTrue(read(ENTRIES_PATH).contains("Component.empty()"),
                "A missing description should be Component.empty() but was:\n" + read(ENTRIES_PATH));
    }

    @Test
    void rootReceivesItsBackground() {
        AdvancementEntity root = advancement("root", null);
        root.setBackground(STONE_BACKGROUND);

        generate(root);

        assertTrue(read(ENTRIES_PATH).contains("\"" + STONE_BACKGROUND + "\""),
                "The background of a root should be part of the entry but was:\n" + read(ENTRIES_PATH));
    }

    @Test
    void mapsFrameTypeToMinestomFrameType() {
        AdvancementEntity root = advancement("root", null);
        root.setFrameType(AdvancementFrameType.GOAL);

        generate(root);

        assertTrue(read(ENTRIES_PATH).contains("FrameType.GOAL"),
                "The frame type GOAL should map to FrameType.GOAL but was:\n" + read(ENTRIES_PATH));
    }

    @Test
    void emitsPositionAndFlags() {
        AdvancementEntity root = advancement("root", null);
        root.setX(1.5f);
        root.setY(-2f);
        root.setShowToast(false);
        root.setHidden(true);

        generate(root);

        assertTrue(read(ENTRIES_PATH).contains("FrameType.TASK, 1.5f, -2.0f, false, true, null)"),
                "The position and flags must be emitted but was:\n" + read(ENTRIES_PATH));
    }

    @Test
    void invalidTitleJsonAbortsWithKeyInMessage() {
        AdvancementEntity broken = advancement("broken_title", null);
        broken.setTitle("{not json");

        IllegalArgumentException exception = assertThrows(IllegalArgumentException.class,
                () -> generate(broken),
                "A title that is not valid JSON must abort the generation");

        assertTrue(exception.getMessage().contains("broken_title"),
                "The message should name the advancement key but was: " + exception.getMessage());
    }

    @Test
    void unknownMaterialAbortsWithKeyInMessage() {
        AdvancementEntity unknown = advancement("unknown_material_adv", null);
        unknown.setMaterial("minecraft:not_a_material");

        IllegalArgumentException exception = assertThrows(IllegalArgumentException.class,
                () -> generate(unknown),
                "An unknown material must abort the generation");

        assertTrue(exception.getMessage().contains("unknown_material_adv") && exception.getMessage().contains("not_a_material"),
                "The message should name the advancement key and the material but was: " + exception.getMessage());
    }

    @Test
    void missingParentAbortsWithKeyInMessage() {
        AdvancementEntity root = advancement("missing_parent", null);
        AdvancementEntity orphan = advancement("orphan", root);

        IllegalArgumentException exception = assertThrows(IllegalArgumentException.class,
                () -> generate(orphan),
                "A parent outside of the project must abort the generation");

        assertTrue(exception.getMessage().contains("orphan") && exception.getMessage().contains("missing_parent"),
                "The message should name the advancement and its missing parent but was: " + exception.getMessage());
    }

    @Test
    void parentCycleAbortsWithKeyInMessage() {
        AdvancementEntity first = advancement("cycle_a", null);
        AdvancementEntity second = advancement("cycle_b", first);
        first.setParent(second);

        IllegalArgumentException exception = assertThrows(IllegalArgumentException.class,
                () -> generate(first, second),
                "A parent cycle must abort the generation");

        assertTrue(exception.getMessage().contains("cycle") && exception.getMessage().contains("cycle_a"),
                "The message should name an advancement of the cycle but was: " + exception.getMessage());
    }

    @Test
    void rejectsTwoKeysWithSameJavaIdentifierNamingBothKeys() {
        IllegalArgumentException exception = assertThrows(IllegalArgumentException.class,
                () -> generate(advancement("my-item", null), advancement("my.item", null)),
                "Two keys that map to the same identifier must abort the generation");

        assertTrue(exception.getMessage().contains("my-item") && exception.getMessage().contains("my.item"),
                "The message must name both keys but was: " + exception.getMessage());
    }

    @Test
    void generatedSourceContainsNoUnresolvedPlaceholders() {
        AdvancementEntity root = advancement("root", null);
        root.setTitle("{\"text\":\"Title\"}");
        root.setBackground(STONE_BACKGROUND);

        generate(root, advancement("child", root));

        for (String path : ALL_PATHS) {
            assertFalse(read(path).contains("$"), "The source " + path + " must not contain any placeholder but was:\n" + read(path));
        }
    }

    @Test
    void generationRunsInReadOnlyTransaction() throws NoSuchMethodException {
        boolean readOnly = AdvancementGenerator.class.getMethod("generate", Path.class, UUID.class).isAnnotationPresent(ReadOnly.class);

        assertTrue(readOnly, "generate must be annotated with @ReadOnly so lazy parent relations can be loaded");
    }

    @Test
    void generatedFilesCompileAgainstVulpesBaseStubs() throws IOException {
        AdvancementEntity root = advancement("root", null);
        root.setTitle("{\"text\":\"Title\"}");
        root.setBackground(STONE_BACKGROUND);
        root.setMaterial("STONE");
        AdvancementEntity child = advancement("child", root);
        child.setFrameType(AdvancementFrameType.CHALLENGE);
        child.setX(1.5f);
        child.setY(-2f);
        child.setHidden(true);
        generate(root, child);

        List<String> sources = new ArrayList<>(writeStubs());
        sources.addAll(ALL_PATHS);

        JavaSourceAssertions.assertCompiles(tempDir, sources.toArray(String[]::new));
    }

    @Test
    void keyWithDashAndDotCompilesAsJavaField() throws IOException {
        generate(advancement("my-item.v2", null));
        List<String> sources = new ArrayList<>(writeStubs());
        sources.addAll(ALL_PATHS);

        JavaSourceAssertions.assertCompiles(tempDir, sources.toArray(String[]::new));
    }

    @Test
    void generatedFilesCompileWithoutAdvancements() throws IOException {
        generate();
        List<String> sources = new ArrayList<>(writeStubs());
        sources.addAll(ALL_PATHS);

        JavaSourceAssertions.assertCompiles(tempDir, sources.toArray(String[]::new));
    }

    @Test
    void generatingTwiceOnTheSameInstanceProducesIdenticalSource() {
        AdvancementEntity root = advancement("root", null);
        AdvancementGenerator generator = generatorWith(root, advancement("child", root));

        generator.generate(tempDir, PROJECT_ID);
        List<String> first = ALL_PATHS.stream().map(this::read).toList();
        generator.generate(tempDir, PROJECT_ID);

        assertEquals(first, ALL_PATHS.stream().map(this::read).toList(),
                "A second run must not change or duplicate the output");
    }

    /**
     * Writes minimal stand-ins for the hand written vulpes-base types the generated code depends on.
     */
    private List<String> writeStubs() throws IOException {
        Map<String, String> stubs = new LinkedHashMap<>();
        stubs.put("stub/net/onelitefeather/vulpes/advancement/CustomAdvancement.java",
                "package net.onelitefeather.vulpes.advancement;\n"
                        + "public sealed interface CustomAdvancement extends CustomAdvancements permits CustomAdvancementImpl {\n"
                        + "    net.kyori.adventure.key.Key key();\n}\n");
        stubs.put("stub/net/onelitefeather/vulpes/advancement/CustomAdvancementImpl.java",
                "package net.onelitefeather.vulpes.advancement;\n"
                        + "import net.kyori.adventure.key.Key;\n"
                        + "import net.kyori.adventure.text.Component;\n"
                        + "import net.minestom.server.advancements.FrameType;\n"
                        + "import net.minestom.server.item.ItemStack;\n"
                        + "record CustomAdvancementImpl(Key key, Key parent, Component title, Component description, ItemStack icon,\n"
                        + "        FrameType frame, float x, float y, boolean showToast, boolean hidden, String background)\n"
                        + "        implements CustomAdvancement {\n"
                        + "    static CustomAdvancement get(Key key) { return CustomAdvancementEntries.entries().stream()\n"
                        + "            .filter(entry -> entry.key().equals(key)).findFirst().orElseThrow(); }\n"
                        + "}\n");
        for (Map.Entry<String, String> stub : stubs.entrySet()) {
            Path file = tempDir.resolve(stub.getKey());
            Files.createDirectories(file.getParent());
            Files.writeString(file, stub.getValue(), UTF_8);
        }
        return new ArrayList<>(stubs.keySet());
    }

    private AdvancementGenerator generatorWith(AdvancementEntity... advancements) {
        when(repository.findByProjectId(eq(PROJECT_ID), any(Pageable.class)))
                .thenReturn(Page.of(List.of(advancements), Pageable.UNPAGED, (long) advancements.length));
        return new AdvancementGenerator(repository);
    }

    private void generate(AdvancementEntity... advancements) {
        generatorWith(advancements).generate(tempDir, PROJECT_ID);
    }

    private String read(String path) {
        try {
            return Files.readString(tempDir.resolve(path), UTF_8);
        } catch (IOException e) {
            throw new AssertionError("The file " + path + " should have been generated", e);
        }
    }

    /**
     * Creates an advancement with a fixed id derived from its key, so every test run sees the same data.
     */
    private AdvancementEntity advancement(String key, AdvancementEntity parent) {
        AdvancementEntity entity = new AdvancementEntity(
                UUID.nameUUIDFromBytes(key.getBytes(UTF_8)),
                "UI " + key,
                key,
                null,
                "minecraft:stone",
                AdvancementFrameType.TASK,
                "{\"text\":\"" + key + "\"}",
                null,
                parent,
                project
        );
        entity.setX(0f);
        entity.setY(0f);
        entity.setShowToast(true);
        entity.setAnnounceToChat(false);
        entity.setHidden(false);
        return entity;
    }
}
