package net.onelitefeather.vulpes.generator.registry;

import io.micronaut.http.HttpResponse;
import io.micronaut.http.HttpStatus;
import net.onelitefeather.vulpes.generator.controller.download.VulpesDownloadController;
import net.onelitefeather.vulpes.generator.generation.Generator;
import net.onelitefeather.vulpes.generator.git.GitProjectWorker;
import org.eclipse.jgit.api.Git;
import org.junit.jupiter.api.BeforeEach;
import org.junit.jupiter.api.Test;
import org.junit.jupiter.api.io.TempDir;

import java.io.File;
import java.io.IOException;
import java.nio.file.Files;
import java.nio.file.Path;
import java.util.ArrayList;
import java.util.List;
import java.util.UUID;
import java.util.concurrent.atomic.AtomicBoolean;
import java.util.zip.ZipEntry;
import java.util.zip.ZipFile;

import static java.nio.charset.StandardCharsets.UTF_8;
import static org.junit.jupiter.api.Assertions.assertEquals;
import static org.junit.jupiter.api.Assertions.assertFalse;
import static org.junit.jupiter.api.Assertions.assertTrue;
import static org.mockito.ArgumentMatchers.any;
import static org.mockito.ArgumentMatchers.anyList;
import static org.mockito.Mockito.mock;
import static org.mockito.Mockito.when;

/**
 * Runs the download pipeline with a real {@link VulpesGeneratorRegistry}, because {@link GeneratorRegistry} is sealed
 * and cannot be mocked. The clone of vulpes-base is replaced by a mocked {@link GitProjectWorker} that writes into the
 * given directory, so no network is used.
 */
class DownloadGenerationTest {

    private static final UUID PROJECT_ID = UUID.fromString("0f8fad5b-d9cb-469f-a165-70867728950e");
    private static final String SOURCE_FOLDER = "src/autogenerated/java";
    private static final String PLACEHOLDER = SOURCE_FOLDER + "/net/onelitefeather/vulpes/attribute/CustomAttributes.java";
    private static final String ITEM_REGISTRY = SOURCE_FOLDER + "/net/onelitefeather/vulpes/item/ItemRegistry.java";

    @TempDir
    Path workDir;

    private GitProjectWorker gitProjectWorker;
    private VulpesGeneratorRegistry registry;
    private VulpesDownloadController controller;

    @BeforeEach
    void setUp() {
        gitProjectWorker = mock(GitProjectWorker.class);
        registry = new VulpesGeneratorRegistry();
        controller = new VulpesDownloadController(registry, gitProjectWorker);
    }

    @Test
    void createsAutogeneratedSourceFolderBeforeGeneratorsRun() {
        when(gitProjectWorker.cloneBaseRepo(any(Path.class), anyList())).thenReturn(mock(Git.class));
        AtomicBoolean sourceFolderExisted = new AtomicBoolean(false);
        registry.add(new RecordingGenerator("folder", (root, projectId) ->
                sourceFolderExisted.set(Files.isDirectory(root.resolve(SOURCE_FOLDER)))));

        controller.generateInto(workDir, "develop", PROJECT_ID);

        assertTrue(sourceFolderExisted.get(), "src/autogenerated/java must exist before the generators write into it");
    }

    @Test
    void returnsServerErrorAndSkipsGeneratorsWhenCloneFails() {
        when(gitProjectWorker.cloneBaseRepo(any(Path.class), anyList())).thenReturn(null);
        AtomicBoolean generatorCalled = new AtomicBoolean(false);
        registry.add(new RecordingGenerator("flag", (root, projectId) -> generatorCalled.set(true)));

        HttpResponse<File> response = controller.generateInto(workDir, "develop", PROJECT_ID);

        assertEquals(HttpStatus.INTERNAL_SERVER_ERROR, response.getStatus(), "A failed clone must answer with a server error");
        assertFalse(generatorCalled.get(), "No generator may run when the clone failed");
    }

    @Test
    void zipContainsGeneratedRegistryNextToPlaceholderWithoutDuplicatingIt() throws IOException {
        when(gitProjectWorker.cloneBaseRepo(any(Path.class), anyList())).thenAnswer(invocation -> {
            writeFile(invocation.getArgument(0), PLACEHOLDER, "placeholder");
            return mock(Git.class);
        });
        registry.add(new RecordingGenerator("item", (root, projectId) -> writeFile(root, ITEM_REGISTRY, "generated")));

        HttpResponse<File> response = controller.generateInto(workDir, "develop", PROJECT_ID);

        assertEquals(HttpStatus.OK, response.getStatus());
        List<String> entries = zipEntries(response.body());
        assertTrue(entries.contains(ITEM_REGISTRY), "The zip must contain the generated registry but had: " + entries);
        assertEquals(1, entries.stream().filter(PLACEHOLDER::equals).count(), "The placeholder must appear exactly once in the zip");
    }

    private static void writeFile(Path output, String relativePath, String content) throws IOException {
        Path file = output.resolve(relativePath);
        Files.createDirectories(file.getParent());
        Files.writeString(file, content, UTF_8);
    }

    private static List<String> zipEntries(File zip) throws IOException {
        List<String> names = new ArrayList<>();
        try (ZipFile zipFile = new ZipFile(zip)) {
            var entries = zipFile.entries();
            while (entries.hasMoreElements()) {
                ZipEntry entry = entries.nextElement();
                if (!entry.isDirectory()) {
                    names.add(entry.getName().replace(File.separatorChar, '/'));
                }
            }
        }
        return names;
    }

    @FunctionalInterface
    private interface Action {
        void run(Path root, UUID projectId) throws IOException;
    }

    /**
     * A generator that runs the given action, used to observe or simulate what the real generators do.
     */
    private record RecordingGenerator(String name, Action action) implements Generator {

        @Override
        public void generate(Path root, UUID projectId) {
            try {
                action.run(root, projectId);
            } catch (IOException e) {
                throw new IllegalStateException(e);
            }
        }

        @Override
        public String getName() {
            return name;
        }

        @Override
        public void cleanup() {
        }
    }
}
